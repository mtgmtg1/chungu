const SLIDE_INTERVAL = 30000;

export default function PoetryProgress({ pct, statusLabel, progressText }) {
  const { t, i18n } = useTranslation();
  const translatedPoems = t("page:poems", { returnObjects: true });
  const poems = Array.isArray(translatedPoems) ? translatedPoems : POEMS;
  const [slideIdx, setSlideIdx] = useState(0);

  useEffect(() => {
    setSlideIdx(Math.floor(Math.random() * poems.length));
  }, [i18n.language]);

  useEffect(() => {
    const timer = setInterval(() => {
      setSlideIdx((prev) => {
        let next;
        do {
          next = Math.floor(Math.random() * poems.length);
        } while (next === prev && poems.length > 1);
        return next;
      });
    }, SLIDE_INTERVAL);
    return () => clearInterval(timer);
  }, [poems.length]);

  const poem = poems[slideIdx];

  return (
    <div
      className="flex-1 flex flex-col items-center justify-center p-5 bg-gradient-to-b from-surface to-surface-container"
      data-oid="poetry-progress"
    >
      {/* 시 슬라이드 */}
      <div
        className="max-w-lg w-full text-center mb-6 transition-opacity duration-1000"
        key={slideIdx}
        data-oid="poem-slide"
      >
        <h3
          className="text-base font-semibold text-on-surface mb-1"
          data-oid="poem-title"
        >
          {poem.title}
        </h3>
        <p
          className="text-sm text-on-surface-variant mb-3"
          data-oid="poem-author"
        >
          — {poem.author}
        </p>
        <div
          className="space-y-1"
          data-oid="poem-lines"
        >
          {poem.lines.map((line, i) => (
            <p
              key={i}
              className={`text-sm ${line === "" ? "h-3" : "text-on-surface-variant"} ${line === "" ? "" : "font-light"}`}
              data-oid={`poem-line-${i}`}
            >
              {line || "\u00A0"}
            </p>
          ))}
        </div>
      </div>

      {/* 로딩바 */}
      <div
        className="w-full max-w-md"
        data-oid="loading-bar"
      >
        <div
          className="flex items-center justify-between mb-2"
          data-oid="loading-header"
        >
          <span
            className="text-sm font-medium text-on-surface"
            data-oid="status-label"
          >
            {statusLabel}
          </span>
          <span
            className="text-sm text-on-surface-variant"
            data-oid="pct-label"
          >
            {pct}%
          </span>
        </div>
        <div
          className="h-1.5 bg-surface-container-high overflow-hidden"
          data-oid="bar-track"
        >
          <div
            className="h-full bg-primary transition-all duration-500 ease-out"
            style={{ width: `${pct}%` }}
            data-oid="bar-fill"
          />
        </div>
        {progressText && (
          <p
            className="text-sm text-on-surface-variant mt-2 text-center"
            data-oid="progress-text"
          >
            {progressText}
          </p>
        )}
        <p
          className="text-xs text-on-surface-variant mt-3 text-center"
          data-oid="leave-notice"
        >
          {t("page:result.leaveNotice")}
        </p>
      </div>
    </div>
  );
}
